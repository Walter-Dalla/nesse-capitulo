const CANONICAL_PATH: Record<Locale, string> = { pt: "/?lang=pt", en: "/", es: "/?lang=es" };

const capitalized = (locale: Locale) => locale[0].toUpperCase() + locale.slice(1);

/** Valores que dependem só do idioma e não são texto: `lang`, canonical e o item atual do seletor. */
function templateValues(locale: Locale): Record<string, string> {
  const values: Record<string, string> = { lang: HTML_LANG[locale], canonicalPath: CANONICAL_PATH[locale] };
  for (const option of LOCALES) {
    values[`langClass${capitalized(option)}`] = option === locale ? "on" : "off";
    values[`langCurrent${capitalized(option)}`] = String(option === locale);
  }
  return values;
}

/** Preenche o modelo `client/landing.html`. Chave ausente lança: melhor quebrar no boot do que servir `{{chave}}`. */
export function renderLanding(template: string, locale: Locale): string {
  const values = { ...LANDING_TEXT[locale], ...templateValues(locale) };
  return template.replace(/\{\{(\w+)\}\}/g, (_match, key: string) => {
    const value = values[key];
    if (value === undefined) throw new Error(`landing.html: chave sem texto em ${locale}: ${key}`);
    return value;
  });
}
